-- Serialize direct privileged Looking For edits too, before the deferred count check.
create function private.activity_lock_profile() returns trigger
language plpgsql security invoker set search_path = '' as $$
begin
    if tg_op = 'UPDATE' and new.user_id <> old.user_id then
        raise exception 'Selection owner is immutable' using errcode = '22023';
    end if;
    perform 1 from public.profiles where id = coalesce(new.user_id, old.user_id) for update;
    return coalesce(new, old);
end;
$$;
create trigger activity_looking_for_lock before insert or update or delete on private.profile_looking_for
    for each row execute function private.activity_lock_profile();

create function private.activity_check_looking_for() returns trigger
language plpgsql security invoker set search_path = '' as $$
declare owner_id uuid := coalesce(new.user_id, old.user_id); choices integer; priorities integer; highest integer;
begin
    select count(*), count(priority_rank), coalesce(max(priority_rank), 0)
        into choices, priorities, highest from private.profile_looking_for where user_id = owner_id;
    if choices > 5 or priorities <> highest or (choices = 0 and exists (
        select 1 from private.profile_setup_progress where user_id = owner_id and looking_for_complete)) then
        raise exception 'Invalid Looking For selections or priority order' using errcode = '23514';
    end if;
    return null;
end;
$$;
create constraint trigger activity_looking_for_invariants after insert or update or delete on private.profile_looking_for
    deferrable initially deferred for each row execute function private.activity_check_looking_for();

-- Retired selections may be retained privately; newly written selections must be published.
create function private.activity_check_published_interest() returns trigger
language plpgsql security invoker set search_path = '' as $$
begin
    if not exists (select 1 from private.activity_interests where id = new.interest_id and published and not age_restricted) then
        raise exception 'Interest unavailable' using errcode = '22023';
    end if;
    return new;
end;
$$;
create trigger activity_profile_interest_published before insert or update on private.profile_activity_interests
    for each row execute function private.activity_check_published_interest();
create trigger activity_filter_interest_published before insert or update on private.discovery_activity_filters
    for each row execute function private.activity_check_published_interest();
revoke all on function private.activity_lock_profile(), private.activity_check_looking_for(),
    private.activity_check_published_interest() from public, anon, authenticated;
grant execute on function private.activity_lock_profile(), private.activity_check_looking_for(),
    private.activity_check_published_interest() to service_role;

